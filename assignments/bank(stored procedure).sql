--check balance based on account number (if customer exists only, if not throw an error msg)
CREATE OR REPLACE PROCEDURE BANK_DB.PUBLIC.CHECK_BALANCE(P_ACCOUNT_NUMBER INT)
RETURNS STRING
LANGUAGE SQL
AS
DECLARE
    V_AMOUNT NUMBER(15,2);
    V_NAME VARCHAR;
BEGIN
    SELECT AMOUNT, CUSTOMER_NAME INTO :V_AMOUNT, :V_NAME
        FROM BANK_DB.PUBLIC.CUSTOMERS WHERE ACCOUNT_NUMBER = :P_ACCOUNT_NUMBER;

    IF (V_AMOUNT IS NULL) THEN
        RETURN 'Error: Customer with account number ' || :P_ACCOUNT_NUMBER || ' not found';
    END IF;

    RETURN 'Customer: ' || :V_NAME || ' | Balance: ' || :V_AMOUNT;
EXCEPTION
    WHEN OTHER THEN
        RETURN 'Error: Customer with account number ' || :P_ACCOUNT_NUMBER || ' not found';
END;


