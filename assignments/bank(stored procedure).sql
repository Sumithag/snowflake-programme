--Deposit amount based on account number (if customer exists only, if not throw an error msg)
CREATE OR REPLACE PROCEDURE BANK_DB.PUBLIC.DEPOSIT(P_ACCOUNT_NUMBER INT, P_AMOUNT NUMBER(15,2))
RETURNS STRING
LANGUAGE SQL
AS
DECLARE
    V_COUNT INT;
    V_NEW_BALANCE NUMBER(15,2);
BEGIN
    SELECT COUNT(*) INTO :V_COUNT
        FROM BANK_DB.PUBLIC.CUSTOMERS WHERE ACCOUNT_NUMBER = :P_ACCOUNT_NUMBER;

    IF (V_COUNT = 0) THEN
        RETURN 'Error: Customer with account number ' || :P_ACCOUNT_NUMBER || ' not found';
    END IF;

    UPDATE BANK_DB.PUBLIC.CUSTOMERS
        SET AMOUNT = AMOUNT + :P_AMOUNT
        WHERE ACCOUNT_NUMBER = :P_ACCOUNT_NUMBER;

    SELECT AMOUNT INTO :V_NEW_BALANCE
        FROM BANK_DB.PUBLIC.CUSTOMERS WHERE ACCOUNT_NUMBER = :P_ACCOUNT_NUMBER;

    RETURN 'Deposit successful. New balance: ' || :V_NEW_BALANCE;
END;


CALL BANK_DB.PUBLIC.DEPOSIT(1001, 5000.00);
CALL BANK_DB.PUBLIC.DEPOSIT(9999, 1000.00);


--withdraw amount based on account number (if customer exists only, if not throw an error msg, check balance sufficient/insufficient)
CREATE OR REPLACE PROCEDURE BANK_DB.PUBLIC.WITHDRAW(P_ACCOUNT_NUMBER INT, P_AMOUNT NUMBER(15,2))
RETURNS STRING
LANGUAGE SQL
AS
DECLARE
    V_COUNT INT;
    V_BALANCE NUMBER(15,2);
    V_NEW_BALANCE NUMBER(15,2);
BEGIN
    SELECT COUNT(*) INTO :V_COUNT
        FROM BANK_DB.PUBLIC.CUSTOMERS WHERE ACCOUNT_NUMBER = :P_ACCOUNT_NUMBER;

    IF (V_COUNT = 0) THEN
        RETURN 'Error: Customer with account number ' || :P_ACCOUNT_NUMBER || ' not found';
    END IF;

    SELECT AMOUNT INTO :V_BALANCE
        FROM BANK_DB.PUBLIC.CUSTOMERS WHERE ACCOUNT_NUMBER = :P_ACCOUNT_NUMBER;

    IF (V_BALANCE < P_AMOUNT) THEN
        RETURN 'Error: Insufficient balance. Current balance: ' || :V_BALANCE;
    END IF;

    UPDATE BANK_DB.PUBLIC.CUSTOMERS
        SET AMOUNT = AMOUNT - :P_AMOUNT
        WHERE ACCOUNT_NUMBER = :P_ACCOUNT_NUMBER;

    SELECT AMOUNT INTO :V_NEW_BALANCE
        FROM BANK_DB.PUBLIC.CUSTOMERS WHERE ACCOUNT_NUMBER = :P_ACCOUNT_NUMBER;

    RETURN 'Withdrawal successful. New balance: ' || :V_NEW_BALANCE;
END;


CALL BANK_DB.PUBLIC.WITHDRAW(1001, 2000.00);
CALL BANK_DB.PUBLIC.WITHDRAW(1001, 999999.00);
CALL BANK_DB.PUBLIC.WITHDRAW(9999, 100.00);





--Display all customers based on branch using cursor (open, fetch, close)
CREATE OR REPLACE PROCEDURE BANK_DB.PUBLIC.GET_CUSTOMERS_BY_BRANCH(P_BRANCH VARCHAR)
RETURNS TABLE(ACCOUNT_NUMBER INT, CUSTOMER_NAME VARCHAR, ADDRESS VARCHAR, PHONE VARCHAR, EMAIL VARCHAR, STATUS VARCHAR, AMOUNT NUMBER(15,2))
LANGUAGE SQL
AS
DECLARE
    V_BRANCH VARCHAR DEFAULT P_BRANCH;
    RES RESULTSET;
BEGIN
    RES := (SELECT ACCOUNT_NUMBER, CUSTOMER_NAME, ADDRESS, PHONE, EMAIL, STATUS, AMOUNT
            FROM BANK_DB.PUBLIC.CUSTOMERS
            WHERE UPPER(BRANCH) = UPPER(:V_BRANCH));
    RETURN TABLE(RES);
END;


